#!/usr/bin/env bash
# Phase 0: READ-ONLY discovery. Changes nothing. Output is markdown (make discover tees it to logs/).
# Optional: TEGRA_SECONDS=120 to sample memory longer (default 60).
set -uo pipefail
S=${TEGRA_SECONDS:-60}
sec() { printf '\n## %s\n\n```\n' "$1"; }
end() { printf '```\n'; }
run() { echo "\$ $*"; eval "$@" 2>&1 | head -${LINES_MAX:-60}; echo; }

echo "# Environment discovery ($(date -Is), host $(hostname))"
sec "Board / L4T";   run cat /etc/nv_tegra_release; run "tr -d '\0' < /proc/device-tree/model; echo"; run "dpkg-query -W nvidia-l4t-core"; end
sec "CUDA / cuDNN / TensorRT"; run "nvcc --version || ls -d /usr/local/cuda*"; run "cat /usr/local/cuda/version.json 2>/dev/null | head -20"
run "dpkg -l | grep -E 'libcudnn|libnvinfer[0-9 ]|tensorrt|nvidia-jetpack|cuda-toolkit' | awk '{print \$2, \$3}'"; end
sec "OS / Python";   run "lsb_release -ds"; run uname -a; run "ldd --version | head -1"; run "python3 --version"; run "python3 -c 'import numpy; print(numpy.__version__)'"; end
sec "Memory / disk"; run free -h; run "swapon --show"; run "df -h / \$HOME"; end
sec "Power mode (read-only)"; run "nvpmodel -q 2>/dev/null || echo 'nvpmodel -q needs sudo'"; end
sec "Docker";        run "docker --version"; run "docker info 2>/dev/null | grep -iE 'runtime|storage driver|docker root'"
run "docker ps --format '{{.Names}}\t{{.Image}}\t{{.Status}}\t{{.Ports}}'"; run "docker images --format '{{.Repository}}:{{.Tag}}\t{{.Size}}' | head -40"; end
sec "Listening ports (check 8080 8090 8091 8092 50051 and Riva/Triton 8000-8002)"; run "ss -ltnup 2>/dev/null | grep LISTEN"; end
sec "Network";       run "ip -br addr"; run "ip route"; run "ip maddr show 2>/dev/null | grep -B2 239.168 || echo 'no 239.168.x membership yet'"
run "for h in pypi.org github.com huggingface.co ghcr.io nvcr.io api.anthropic.com; do printf '%-20s ' \$h; timeout 4 bash -c \"exec 3<>/dev/tcp/\$h/443\" 2>/dev/null && echo reachable || echo unreachable; done"; end
sec "Unitree SDK";   run "python3 -c 'import unitree_sdk2py, os; print(os.path.dirname(unitree_sdk2py.__file__))' 2>&1"
run "ls -d \$HOME/unitree_sdk2* /opt/unitree* /unitree 2>/dev/null"; run "env | grep -iE 'cyclone|ros_domain|rmw' || true"; end
sec "Camera";        run "ls -l /dev/video* 2>/dev/null"; run "lsusb | grep -iE 'intel|realsense|camera' || true"; run "v4l2-ctl --list-devices 2>/dev/null"; end
sec "Audio (local devices; G1 audio is NOT here)"; run "pactl list short sinks 2>/dev/null; pactl list short sources 2>/dev/null"; end
sec "CPU load / processes (top 15 by memory)"; run "uptime"; run "ps -eo pid,comm,%cpu,%mem,rss --sort=-rss | head -16"; end
sec "tegrastats for ${S}s (1 sample/s; RAM, SWAP, temps)"
if command -v tegrastats >/dev/null; then timeout "$S" tegrastats --interval 1000 2>&1 | awk 'NR%5==1'; else echo "tegrastats not found"; fi
end
echo; echo "_Generated by scripts/discover_env.sh; copy the relevant parts into docs/ENVIRONMENT.md._"
